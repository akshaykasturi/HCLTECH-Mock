"""Build app/uc4/causes.yaml: a temporary cause catalog until policy.yaml lands.

Uses TRAIN data only:
  - class, first_check, requires_escalation: from the train cases' labels (one value per cause);
  - key_signals and confirming_signals: from derived/likelihoods.learned.yaml (learned on train).

Rules (written here so anyone can re-run and check them):
  ratio(s, c) = P(s | c) / mean over the other causes of P(s | other)   ("how specific is s to c")
  key_signals:       among signals that are not status_*, code_*, msg_* or missing-data signals,
                     keep those with ratio >= MIN_KEY_RATIO; take the highest likelihood,
                     up to 2 signals tied at that likelihood (higher ratio first).
  confirming_signals: the cause's specific error-code signal (code_* or msg_*, not generic,
                     highest likelihood, ratio >= MIN_KEY_RATIO) if it has one, plus its key signals.

Usage (from backend):  .\\.venv\\Scripts\\python.exe scripts\\build_causes.py
"""
import json
import sys
from pathlib import Path

import yaml

BACKEND = Path(__file__).resolve().parents[1]
EVAL = BACKEND / "data" / "eval" / "uc4"
OUT = BACKEND / "app" / "uc4" / "causes.yaml"

MIN_KEY_RATIO = 1.8
MAX_KEY_SIGNALS = 2
# Signals that say "data is missing": never a key signal of a cause.
MISSING_DATA_SIGNALS = {"metrics_missing", "dep_metrics_missing", "auth_fields_missing", "isolated_failure",
                        "ratelimit_headers_missing", "window_logs_missing"}


def _is_code(signal: str) -> bool:
    return signal.startswith(("code_", "msg_"))


def _ratio(likelihoods: dict, cause: str, signal: str) -> float:
    others = [c for c in likelihoods if c != cause]
    return likelihoods[cause][signal] / (sum(likelihoods[o][signal] for o in others) / len(others))


def key_signals(likelihoods: dict, cause: str) -> list[str]:
    candidates = [
        s for s in likelihoods[cause]
        if not s.startswith("status_") and not _is_code(s) and s not in MISSING_DATA_SIGNALS
        and _ratio(likelihoods, cause, s) >= MIN_KEY_RATIO
    ]
    if not candidates:
        return []
    best = max(likelihoods[cause][s] for s in candidates)
    tied = [s for s in candidates if likelihoods[cause][s] == best]
    tied.sort(key=lambda s: -_ratio(likelihoods, cause, s))
    return tied[:MAX_KEY_SIGNALS]


def code_signal(likelihoods: dict, cause: str) -> str | None:
    codes = [s for s in likelihoods[cause] if _is_code(s) and "generic" not in s
             and _ratio(likelihoods, cause, s) >= MIN_KEY_RATIO]
    if not codes:
        return None
    return max(codes, key=lambda s: (likelihoods[cause][s], _ratio(likelihoods, cause, s)))


def main() -> int:
    likelihoods = yaml.safe_load((EVAL / "derived" / "likelihoods.learned.yaml").read_text(encoding="utf-8"))
    train_ids = set((EVAL / "splits" / "train.txt").read_text(encoding="utf-8").split())
    labels: dict[str, dict] = {}
    for line in (EVAL / "cases.jsonl").read_text(encoding="utf-8").splitlines():
        case = json.loads(line)
        if case["case_id"] not in train_ids or not case["expected_cause"]:
            continue
        row = {"class": case["expected_class"], "first_check": case["expected_first_check"],
               "requires_escalation": case["requires_escalation"]}
        previous = labels.setdefault(case["expected_cause"], row)
        if previous != row:
            print(f"inconsistent labels for {case['expected_cause']}: {previous} vs {row}")
            return 1

    missing = set(likelihoods) ^ set(labels)
    if missing:
        print(f"causes in likelihoods and train labels differ: {sorted(missing)}")
        return 1

    catalog = {}
    for cause in sorted(likelihoods):
        keys = key_signals(likelihoods, cause)
        code = code_signal(likelihoods, cause)
        catalog[cause] = {**labels[cause], "key_signals": keys,
                          "confirming_signals": ([code] if code else []) + keys}

    header = ("# Temporary cause catalog until policy.yaml lands. GENERATED by scripts/build_causes.py\n"
              "# from train-split labels and derived/likelihoods.learned.yaml. Do not edit by hand.\n")
    OUT.write_text(header + yaml.safe_dump(catalog, sort_keys=False), encoding="utf-8")
    print(f"wrote {OUT.relative_to(BACKEND)} ({len(catalog)} causes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
